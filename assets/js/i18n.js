function getLanguage() {
    return localStorage.getItem('vitasense_lang') || 'en';
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('vitasense_lang', lang);
    applyTranslations(lang);
    updateLangDropdownUI(lang);
}

function updateLangDropdownUI(lang) {
    const labelElem = document.getElementById('currentLangLabel');
    if (!labelElem) return;
    if (lang === 'hi') {
        labelElem.innerHTML = '🇮🇳 हिंदी';
    } else if (lang === 'ta') {
        labelElem.innerHTML = '🇮🇳 தமிழ்';
    } else {
        labelElem.innerHTML = '🇬🇧 English';
    }
}

function applyTranslations(lang) {
    const dict = translations[lang] || translations['en'];
    
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                const icon = el.querySelector('i');
                if (icon) {
                    const iconClone = icon.cloneNode(true);
                    el.textContent = ' ' + dict[key];
                    el.prepend(iconClone);
                } else {
                    el.textContent = dict[key];
                }
            }
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const currentLang = getLanguage();
    updateLangDropdownUI(currentLang);
    applyTranslations(currentLang);
});
